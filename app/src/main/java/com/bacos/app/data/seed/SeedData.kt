    /** Seed the curriculum into Room. Idempotent — skipped when already seeded. */
    suspend fun seed(db: AppDb) {
        if (db.subjectDao().count() > 0) return

        subjects.forEachIndexed { si, s ->
            val subjectId = db.subjectDao().insertAll(
                listOf(SubjectEntity(code = s.code, nameAr = s.nameAr, nameFr = s.nameFr, colorHex = s.colorHex, orderIdx = si))
            ).first()

            s.chapters.forEachIndexed { ci, ch ->
                val chapterId = db.chapterDao().insertAll(
                    listOf(ChapterEntity(subjectId = subjectId, nameAr = ch.nameAr, nameFr = ch.nameFr, orderIdx = ci))
                ).first()

                ch.lessons.forEach { l ->
                    val lessonId = db.lessonDao().insert(
                        LessonEntity(
                            chapterId = chapterId,
                            titleAr = l.title,
                            summary = l.summary,
                            difficulty = l.difficulty,
                            minutes = l.minutes,
                            sectionsJson = sectionsJson(l.sections),
                        )
                    )

                    if (l.questions.isNotEmpty()) {
                        db.questionDao().insertAll(
                            l.questions.map { q ->
                                QuestionEntity(
                                    lessonId = lessonId,
                                    text = q.text,
                                    choicesJson = choicesJson(q.choices),
                                    correctIndex = q.correct,
                                    difficulty = q.diff,
                                    explanation = q.explanation,
                                    concept = q.concept,
                                )
                            }
                        )
                    }

                    if (l.cards.isNotEmpty()) {
                        db.flashcardDao().insertAll(
                            l.cards.map { c -> FlashcardEntity(lessonId = lessonId, front = c.front, back = c.back) }
                        )
                    }
                }
            }
        }
    }
